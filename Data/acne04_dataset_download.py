import ipywidgets as widgets
from IPython.display import display
from matplotlib.widgets import RectangleSelector
from PIL import Image

# Select the image to annotate
image_index = 0

row = df.iloc[image_index]
image = Image.open(row["image_path"]).convert("RGB")

# Load existing annotations
boxes = json.loads(row["lesion_boxes"])

# Store additional boxes
new_boxes = []

fig, ax = plt.subplots(figsize=(9, 9))
ax.imshow(image)
ax.set_title("Drag your mouse to draw additional acne boxes")

# Display existing boxes in red
for i in range(len(boxes["xmin"])):
    ax.add_patch(
        patches.Rectangle(
            (boxes["xmin"][i], boxes["ymin"][i]),
            boxes["xmax"][i] - boxes["xmin"][i],
            boxes["ymax"][i] - boxes["ymin"][i],
            linewidth=2,
            edgecolor="red",
            facecolor="none"
        )
    )

# Function to draw new boxes
def on_select(eclick, erelease):

    if eclick.xdata is None or erelease.xdata is None:
        return

    xmin = int(min(eclick.xdata, erelease.xdata))
    ymin = int(min(eclick.ydata, erelease.ydata))
    xmax = int(max(eclick.xdata, erelease.xdata))
    ymax = int(max(eclick.ydata, erelease.ydata))

    width, height = image.size

    xmin = max(0, min(xmin, width))
    xmax = max(0, min(xmax, width))
    ymin = max(0, min(ymin, height))
    ymax = max(0, min(ymax, height))

    if xmax <= xmin or ymax <= ymin:
        return

    new_boxes.append({
        "xmin": xmin,
        "ymin": ymin,
        "xmax": xmax,
        "ymax": ymax
    })

    ax.add_patch(
        patches.Rectangle(
            (xmin, ymin),
            xmax - xmin,
            ymax - ymin,
            linewidth=2,
            edgecolor="lime",
            facecolor="none"
        )
    )

    fig.canvas.draw_idle()

# Activate rectangle drawing
selector = RectangleSelector(
    ax,
    on_select,
    useblit=False,
    button=[1],
    minspanx=3,
    minspany=3,
    spancoords="pixels",
    interactive=False
)

plt.show()

# Finish button
finish_button = widgets.Button(
    description="Finish Annotation",
    button_style="success"
)

def finish_annotation(button):
    selector.set_active(False)

    print("\nNew bounding boxes added:", len(new_boxes))

    for i, box in enumerate(new_boxes):
        print(f"Box {i+1}: {box}")

finish_button.on_click(finish_annotation)

display(finish_button)