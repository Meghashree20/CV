annotation_issues = []

for _, row in df.iterrows():
    try:
        boxes = json.loads(row["lesion_boxes"])

        keys = ["xmin", "ymin", "xmax", "ymax"]
        if not all(key in boxes for key in keys):
            annotation_issues.append((row["filename"], "Missing coordinate key"))
            continue

        lengths = [len(boxes[key]) for key in keys]
        if len(set(lengths)) != 1:
            annotation_issues.append((row["filename"], "Coordinate arrays have different lengths"))
            continue

        box_count = lengths[0]
        if box_count != int(row["lesion_count"]):
            annotation_issues.append((row["filename"], "Stored lesion count differs from box count"))
            continue

        with Image.open(row["image_path"]) as img:
            width, height = img.size

        for i in range(box_count):
            xmin, ymin = boxes["xmin"][i], boxes["ymin"][i]
            xmax, ymax = boxes["xmax"][i], boxes["ymax"][i]

            if not (0 <= xmin < xmax <= width and 0 <= ymin < ymax <= height):
                annotation_issues.append((row["filename"], f"Invalid/out-of-bounds box at index {i}"))
                break

    except Exception as exc:
        annotation_issues.append((row["filename"], f"Could not parse annotation: {exc}"))

print("Images checked:", len(df))
print("Images with annotation structure/coordinate issues:", len(annotation_issues))

if annotation_issues:
    display(pd.DataFrame(annotation_issues, columns=["filename", "issue"]).head(30))
else:
    print("All stored box arrays, counts and coordinate bounds passed these checks.")

print("\nNote: This checks annotation structure and coordinate validity, not whether every visible acne lesion was labelled.")

