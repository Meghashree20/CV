import cv2
import matplotlib.pyplot as plt
from pathlib import Path

BASE_DIR = Path("/content/gdrive/MyDrive/SkinCare_AI/ACNE04")

IMAGE_DIR = BASE_DIR / "yolo_dataset_v1/images/validation"
GT_DIR = BASE_DIR / "yolo_dataset_v1/labels/validation"

PRED_DIR = (
    BASE_DIR
    / "model_outputs/error_analysis/validation_predictions/labels"
)

# Select 8 validation images
image_files = sorted(IMAGE_DIR.glob("*.jpg"))[:8]

fig, axes = plt.subplots(4, 2, figsize=(14, 20))
axes = axes.flatten()

for i, image_path in enumerate(image_files):

    image = cv2.imread(str(image_path))
    image = cv2.cvtColor(image, cv2.COLOR_BGR2RGB)

    height, width = image.shape[:2]

    gt_file = GT_DIR / f"{image_path.stem}.txt"
    pred_file = PRED_DIR / f"{image_path.stem}.txt"

    # Draw ground-truth boxes in green
    if gt_file.exists():
        for line in gt_file.read_text().splitlines():
            values = list(map(float, line.split()[:5]))
            _, x, y, w, h = values

            x1 = int((x - w / 2) * width)
            y1 = int((y - h / 2) * height)
            x2 = int((x + w / 2) * width)
            y2 = int((y + h / 2) * height)

            cv2.rectangle(image, (x1, y1), (x2, y2), (0, 255, 0), 2)

    # Draw predicted boxes in red
    if pred_file.exists():
        for line in pred_file.read_text().splitlines():
            values = list(map(float, line.split()[:5]))
            _, x, y, w, h = values

            x1 = int((x - w / 2) * width)
            y1 = int((y - h / 2) * height)
            x2 = int((x + w / 2) * width)
            y2 = int((y + h / 2) * height)

            cv2.rectangle(image, (x1, y1), (x2, y2), (255, 0, 0), 2)

    axes[i].imshow(image)
    axes[i].set_title(image_path.name)
    axes[i].axis("off")

plt.tight_layout()
plt.show()